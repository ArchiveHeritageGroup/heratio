<?php

/**
 * ahg:library-email-circulation-report
 *
 * Scheduled circulation statistics by email (#1476), following the pattern of
 * EmailUsageReportsCommand. Sends the last complete period as CSV + PDF.
 *
 * Settings (ahg_settings):
 *   circulation_report_email_enabled     bool    master switch (default off)
 *   circulation_report_email_recipients  csv     email addresses
 *   circulation_report_email_period      string  library_report_period code:
 *                                                monthly (default), quarterly, yearly
 *   circulation_report_email_branch      int     repository id; empty = all branches
 *   circulation_report_email_from_name   string  From display name
 *
 * The cron_schedule row runs this monthly and ships disabled. A quarterly or
 * yearly setting sends only in the first month of the new period, and a period
 * already sent is not sent again.
 *
 * Copyright (C) 2026 Johan Pieterse - Plain Sailing Information Systems - AGPL-3.0
 */

namespace AhgLibrary\Console\Commands;

use AhgCore\Services\AhgSettingsService;
use AhgLibrary\Services\LibraryCirculationStatsService;
use Illuminate\Console\Command;
use Illuminate\Database\Schema\Blueprint;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Facades\Schema;
use Throwable;

class EmailCirculationReportCommand extends Command
{
    protected $signature = 'ahg:library-email-circulation-report
        {--dry-run : Build the report but do not send the email}
        {--force   : Send even if switched off, not due, or already sent (still requires recipients)}';

    protected $description = 'Email the last complete period\'s circulation statistics to the configured recipients.';

    public function handle(LibraryCirculationStatsService $stats): int
    {
        $force = (bool) $this->option('force');

        if (! AhgSettingsService::getBool('circulation_report_email_enabled', false) && ! $force) {
            $this->info('circulation_report_email_enabled is off - skipping.');

            return self::SUCCESS;
        }

        $recipients = array_values(array_filter(
            array_map('trim', explode(',', (string) AhgSettingsService::get('circulation_report_email_recipients', ''))),
            fn ($e) => filter_var($e, FILTER_VALIDATE_EMAIL)
        ));
        if ($recipients === []) {
            $this->warn('No recipients configured. Set ahg_settings.circulation_report_email_recipients.');

            return self::SUCCESS;
        }

        $period = strtolower((string) (AhgSettingsService::get('circulation_report_email_period', 'monthly') ?: 'monthly'));
        if (! in_array($period, ['monthly', 'quarterly', 'yearly'], true)) {
            $this->error("Unsupported circulation_report_email_period: {$period}");

            return self::FAILURE;
        }
        if (! $force && ! $this->isDue($period)) {
            $this->info("Not the first month of a new {$period} period - skipping.");

            return self::SUCCESS;
        }

        [$from, $to] = $stats->resolvePeriod($period);
        $branch = AhgSettingsService::getInt('circulation_report_email_branch', 0);
        $key = 'CIRCULATION' . ($branch > 0 ? ':' . $branch : '');

        if (! $force && $this->alreadySent($key, $from, $to)) {
            $this->info("Already sent for {$from} to {$to} - skipping.");

            return self::SUCCESS;
        }

        try {
            $report = $stats->build($from, $to, $branch > 0 ? [$branch] : null);
            $csv = $stats->toCsv($report);
            $pdf = $stats->toPdf($report);
        } catch (Throwable $e) {
            $this->error('Report build failed: ' . $e->getMessage());
            $this->logSend($recipients, $key, $from, $to, 'failed', $e->getMessage());

            return self::FAILURE;
        }

        if ($this->option('dry-run')) {
            $this->info('--dry-run: skipping send. Would send to: ' . implode(', ', $recipients));
            $this->logSend($recipients, $key, $from, $to, 'dry_run', null);

            return self::SUCCESS;
        }

        $name = "circulation-{$from}-{$to}";
        $subject = sprintf('[Heratio] Circulation statistics %s to %s (%s)', $from, $to, $report['branch_label']);
        $body = sprintf(
            "Attached are the circulation statistics for %s to %s (%s).\n\nIssues: %d\nReturns: %d\nActive borrowers: %d\n\nGenerated by Heratio (%s) on %s.\n",
            $from, $to, $report['branch_label'],
            $report['summary']['issues'], $report['summary']['returns'], $report['summary']['active_borrowers'],
            (string) (config('app.url') ?: 'heratio'), now()->toIso8601String()
        );
        $fromName = AhgSettingsService::get('circulation_report_email_from_name');

        try {
            Mail::raw($body, function ($m) use ($recipients, $subject, $csv, $pdf, $name, $fromName) {
                $m->to($recipients)->subject($subject);
                if ($fromName && ($address = config('mail.from.address'))) {
                    $m->from($address, $fromName);
                }
                $m->attachData($csv, $name . '.csv', ['mime' => 'text/csv']);
                $m->attachData($pdf, $name . '.pdf', ['mime' => 'application/pdf']);
            });
        } catch (Throwable $e) {
            $this->error('Send failed: ' . $e->getMessage());
            $this->logSend($recipients, $key, $from, $to, 'failed', $e->getMessage());

            return self::FAILURE;
        }

        $this->info('Sent to: ' . implode(', ', $recipients));
        $this->logSend($recipients, $key, $from, $to, 'sent', null);

        return self::SUCCESS;
    }

    private function isDue(string $period): bool
    {
        $month = (int) now()->month;

        return match ($period) {
            'quarterly' => in_array($month, [1, 4, 7, 10], true),
            'yearly' => $month === 1,
            default => true,
        };
    }

    private function alreadySent(string $key, string $from, string $to): bool
    {
        return Schema::hasTable('library_usage_email_log')
            && DB::table('library_usage_email_log')
                ->where('report_ids', $key)
                ->where('begin_date', $from)
                ->where('end_date', $to)
                ->where('status', 'sent')
                ->exists();
    }

    /** Best-effort: logging must never fail the run. */
    private function logSend(array $recipients, string $key, string $from, string $to, string $status, ?string $error): void
    {
        try {
            if (! Schema::hasTable('library_usage_email_log')) {
                Schema::create('library_usage_email_log', function (Blueprint $t) {
                    $t->bigIncrements('id');
                    $t->text('recipients');
                    $t->string('report_ids', 120);
                    $t->date('begin_date');
                    $t->date('end_date');
                    $t->string('status', 16)->index('ix_status');
                    $t->text('error')->nullable();
                    $t->timestamp('created_at')->useCurrent()->index('ix_created');
                });
            }
            DB::table('library_usage_email_log')->insert([
                'recipients' => implode(',', $recipients),
                'report_ids' => $key,
                'begin_date' => $from,
                'end_date' => $to,
                'status' => $status,
                'error' => $error,
                'created_at' => now(),
            ]);
        } catch (Throwable) {
            // never let logging break the command
        }
    }
}
