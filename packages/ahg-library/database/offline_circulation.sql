CREATE TABLE IF NOT EXISTS library_offline_rule_snapshot (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    rules_hash CHAR(64) NOT NULL,
    rules_json LONGTEXT NOT NULL,
    default_loan_days_json TEXT NOT NULL COMMENT 'branch id => default loan days; 0 = installation default',
    effective_from DATETIME NOT NULL,
    source VARCHAR(30) NOT NULL COMMENT 'what recorded this version of the rules',
    created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_offline_snapshot_effective (effective_from, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS library_offline_txn (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    client_uuid CHAR(36) NOT NULL,
    device_id VARCHAR(64) NOT NULL,
    seq INT UNSIGNED NOT NULL,
    action VARCHAR(20) NOT NULL COMMENT 'ahg_dropdown library_offline_action',
    copy_barcode VARCHAR(50) NOT NULL,
    copy_id BIGINT UNSIGNED NULL,
    patron_card VARCHAR(50) NULL,
    patron_id BIGINT UNSIGNED NULL,
    expected_patron_card VARCHAR(50) NULL COMMENT 'borrower the desk believed held the copy at return',
    branch_id INT NULL,
    occurred_at DATETIME NOT NULL COMMENT 'UTC, from the desk clock',
    received_at DATETIME NOT NULL,
    rule_snapshot_id BIGINT UNSIGNED NULL,
    rule_basis VARCHAR(20) NULL COMMENT 'as_at, or earliest_known when no older version was recorded',
    status VARCHAR(20) NOT NULL DEFAULT 'pending' COMMENT 'ahg_dropdown library_offline_status',
    conflict_code VARCHAR(40) NULL COMMENT 'ahg_dropdown library_offline_conflict',
    conflict_detail TEXT NULL,
    checkout_id BIGINT UNSIGNED NULL,
    due_date DATE NULL,
    captured_by INT UNSIGNED NULL,
    resolved_by INT UNSIGNED NULL,
    resolved_at DATETIME NULL,
    resolution VARCHAR(20) NULL COMMENT 'ahg_dropdown library_offline_resolution',
    resolution_note TEXT NULL,
    overrides VARCHAR(120) NULL COMMENT 'comma list of policy checks staff chose to override',
    created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_offline_txn_uuid (client_uuid),
    KEY idx_offline_txn_device (captured_by, device_id, seq),
    KEY idx_offline_txn_status (status, occurred_at),
    KEY idx_offline_txn_copy (copy_barcode, status, occurred_at),
    KEY idx_offline_txn_branch (branch_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

